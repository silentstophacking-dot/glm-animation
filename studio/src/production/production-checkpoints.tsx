import React from 'react';
import {Composition,registerRoot} from 'remotion';
import {ProductionScene} from './scene-system';
import {environmentPreset} from './environment-presets';
const duration=180;
const night=environmentPreset('night-street','preset-night',duration);
const apartment=environmentPreset('apartment','preset-apartment',duration);
const industrial=environmentPreset('industrial-interior','preset-industrial',duration);
const Root=()=> <><Composition id="PresetNightStreet" component={ProductionScene} defaultProps={{spec:night}} durationInFrames={duration} fps={30} width={1920} height={1080}/><Composition id="PresetApartment" component={ProductionScene} defaultProps={{spec:apartment}} durationInFrames={duration} fps={30} width={1920} height={1080}/><Composition id="PresetIndustrial" component={ProductionScene} defaultProps={{spec:industrial}} durationInFrames={duration} fps={30} width={1920} height={1080}/></>;
registerRoot(Root);
